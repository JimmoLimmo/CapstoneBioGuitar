"""Build left_hand.xml (and mesh_left/) as the mirror image of right_hand.xml.

    python3 Sim/MPL/make_left_hand.py

Mirrors across the model's x = 0 plane. Joint axes are flipped too, so a
positive joint angle bends a left finger the same way it bends a right one and
both hands take the same poses.
"""

import os
import struct
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, "right_hand.xml")
TARGET = os.path.join(HERE, "left_hand.xml")
MESH_IN = os.path.join(HERE, "mesh")
MESH_OUT = os.path.join(HERE, "mesh_left")


def nums(text):
    return [float(v) for v in text.split()]


def text(values):
    return " ".join("0" if abs(v) < 1e-12 else f"{v:.9g}" for v in values)


# Point or direction: x changes sign.
def point(v):
    return [-v[0], v[1], v[2]]


# Rotation axis: the mirror image of a turn about a is a turn about -M a.
def axis(v):
    return [v[0], -v[1], -v[2]]


def quat(q):
    return [q[0], q[1], -q[2], -q[3]]


def mirror_element(el):
    a = el.attrib
    if "pos" in a:
        a["pos"] = text(point(nums(a["pos"])))
    if "quat" in a:
        a["quat"] = text(quat(nums(a["quat"])))
    if "axis" in a:
        a["axis"] = text(axis(nums(a["axis"])))
    if "axisangle" in a:
        v = nums(a["axisangle"])
        a["axisangle"] = text(axis(v[:3]) + v[3:])
    if "zaxis" in a:
        a["zaxis"] = text(point(nums(a["zaxis"])))
    if "fromto" in a:
        v = nums(a["fromto"])
        a["fromto"] = text(point(v[:3]) + point(v[3:]))
    if el.tag == "statistic" and "center" in a:
        a["center"] = text(point(nums(a["center"])))


# Binary STL with x negated; the corner order flips so the faces still point out.
def mirror_stl(src, dst):
    with open(src, "rb") as f:
        data = f.read()
    if data[:5] == b"solid" and b"facet" in data[:512]:
        raise SystemExit(f"{src} is ASCII STL; only binary is handled")
    count = struct.unpack("<I", data[80:84])[0]
    out = [data[:80], struct.pack("<I", count)]
    for i in range(count):
        v = struct.unpack("<12fH", data[84 + 50 * i: 134 + 50 * i])
        n, p0, p1, p2 = v[0:3], v[3:6], v[6:9], v[9:12]
        out.append(struct.pack("<12fH", *point(n), *point(p0), *point(p2), *point(p1), v[12]))
    with open(dst, "wb") as f:
        f.write(b"".join(out))


def main():
    tree = ET.parse(SOURCE, ET.XMLParser(target=ET.TreeBuilder(insert_comments=True)))
    root = tree.getroot()
    root.set("model", "MPL_left")
    root.find("compiler").set("meshdir", "mesh_left/")
    for el in root.iter():
        if isinstance(el.tag, str) and el.tag not in ("mesh", "texture", "material"):
            mirror_element(el)

    os.makedirs(MESH_OUT, exist_ok=True)
    meshes = [m.get("file") for m in root.iter("mesh") if m.get("file")]
    for name in meshes:
        mirror_stl(os.path.join(MESH_IN, name), os.path.join(MESH_OUT, name))

    note = ET.Comment(" Generated by make_left_hand.py from right_hand.xml (mirror image). Edit that file and re-run instead. ")
    root.insert(0, note)
    tree.write(TARGET, encoding="unicode")
    print(f"wrote {os.path.relpath(TARGET)} and {len(meshes)} meshes in {os.path.relpath(MESH_OUT)}")


if __name__ == "__main__":
    main()
